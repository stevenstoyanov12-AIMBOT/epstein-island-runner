using System.Collections.Generic;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering;

// Builds the "Statue Garden" scene (draped portrait bust and an autumn tree): Tools > Build Statue Scene.
public static class StatueSceneBuilder
{
    const string ScenePath = "Assets/Scenes/StatueGarden.unity";
    const string MaterialFolder = "Assets/Materials";

    [MenuItem("Tools/Build Statue Scene")]
    public static void Build()
    {
        if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo()) return;

        var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);

        var marble = GetMaterial("Marble", new Color(0.90f, 0.88f, 0.83f), 0.6f, 0f);
        var stone = GetMaterial("Stone", new Color(0.62f, 0.60f, 0.57f), 0.2f, 0f);
        var grass = GetMaterial("Grass", new Color(0.32f, 0.5f, 0.25f), 0.1f, 0f);
        var path = GetMaterial("Path", new Color(0.62f, 0.56f, 0.47f), 0.15f, 0f);

        // Lighting
        var sun = new GameObject("Sun").AddComponent<Light>();
        sun.type = LightType.Directional;
        sun.intensity = 1.3f;
        sun.shadows = LightShadows.Soft;
        sun.color = new Color(1f, 0.95f, 0.86f);
        sun.transform.rotation = Quaternion.Euler(45f, -35f, 0f);
        RenderSettings.ambientMode = AmbientMode.Trilight;
        RenderSettings.ambientSkyColor = new Color(0.55f, 0.65f, 0.8f);
        RenderSettings.ambientEquatorColor = new Color(0.45f, 0.45f, 0.42f);
        RenderSettings.ambientGroundColor = new Color(0.2f, 0.22f, 0.18f);

        // Ground and plaza
        var env = new GameObject("Environment").transform;
        Part(PrimitiveType.Plane, "Ground", env, Vector3.zero, new Vector3(6f, 1f, 6f), grass);
        Part(PrimitiveType.Cylinder, "Plaza", env, new Vector3(0f, 0.05f, 0f), new Vector3(22f, 0.05f, 22f), path);

        // Portrait bust wearing a marble drape, on a pedestal in front of the start
        var statues = new GameObject("Statues").transform;
        var bust = Bust("Bust_Portrait", statues, new Vector3(0f, 0f, -1.5f), marble, stone);

        // Autumn tree behind the bust (meshes generated by tools/statue_gen/autumn_tree.py)
        AutumnTree("AutumnTree", env, new Vector3(0f, 0.1f, 3f));

        // BATON crates beside the tree, and the van interior (off to the side) for the crate cutscene
        var crates = CrateMaterials();
        Crate("Crate_Plaza_1", env, new Vector3(2.6f, 0.1f, 1.2f), 20f, crates);
        Crate("Crate_Plaza_2", env, new Vector3(3.5f, 0.1f, 2.1f), -12f, crates);
        Crate("Crate_Plaza_3", env, new Vector3(2.7f, 0.1f + CrateHeight, 1.25f), 8f, crates);
        CutsceneVan(new Vector3(200f, 0f, 0f), crates);  // far off, out of sight of the plaza

        // Camera looking at the plaza
        var cam = new GameObject("Main Camera");
        cam.tag = "MainCamera";
        cam.AddComponent<Camera>().fieldOfView = 60f;
        cam.AddComponent<AudioListener>();
        cam.AddComponent<FlyCamera>();
        // player eye height, looking past the bust to the tree
        cam.transform.position = new Vector3(0f, 1.7f, -4f);
        cam.transform.LookAt(bust.transform.position + Vector3.up * 1.6f);

        EditorSceneManager.SaveScene(scene, ScenePath);
        AddToBuildSettings(ScenePath);
        Debug.Log($"Statue scene built and saved to {ScenePath}");
    }

    const string TreeFolder = "Assets/Models/Trees";

    // Blender-built tree (tools/blender_tree): displaced bark with albedo + normal maps,
    // and maple-leaf cards cut out of a texture atlas with alpha clipping, rendered two-sided.
    static void AutumnTree(string name, Transform parent, Vector3 position)
    {
        var root = new GameObject(name);
        root.transform.SetParent(parent, false);
        root.transform.localPosition = position;

        var bark = GetMaterial("Bark", Color.white, 0.1f, 0f);
        bark.SetTexture("_BaseMap", LoadTexture($"{TreeFolder}/Textures/bark_albedo.png", false));
        bark.SetTexture("_BumpMap", LoadTexture($"{TreeFolder}/Textures/bark_normal.png", true));
        bark.EnableKeyword("_NORMALMAP");

        var leaves = GetMaterial("Leaves", Color.white, 0.3f, 0f);
        leaves.SetTexture("_BaseMap", LoadTexture($"{TreeFolder}/Textures/leaves_atlas.png", false));
        leaves.SetTexture("_BumpMap", LoadTexture($"{TreeFolder}/Textures/leaves_normal.png", true));
        leaves.EnableKeyword("_NORMALMAP");
        leaves.SetFloat("_AlphaClip", 1f);
        leaves.SetFloat("_Cutoff", 0.5f);
        leaves.EnableKeyword("_ALPHATEST_ON");
        leaves.SetFloat("_Cull", (float)CullMode.Off);
        leaves.doubleSidedGI = true;
        EditorUtility.SetDirty(leaves);

        var trunk = AddMesh(root.transform, "Bark", $"{TreeFolder}/Tree_Bark.fbx", bark);
        if (trunk != null)
            trunk.AddComponent<MeshCollider>().sharedMesh = trunk.GetComponent<MeshFilter>().sharedMesh;
        var crown = AddMesh(root.transform, "Leaves", $"{TreeFolder}/Tree_Leaves.fbx", leaves);
        if (crown != null)
        {
            var falling = root.AddComponent<FallingLeaves>();
            // the editor can read imported meshes; every 9th vertex spreads points over the whole crown
            var verts = crown.GetComponent<MeshFilter>().sharedMesh.vertices;
            falling.spawnPoints = new Vector3[verts.Length / 9];
            for (int i = 0; i < falling.spawnPoints.Length; i++)
                falling.spawnPoints[i] = verts[i * 9];
            falling.leafMaterial = leaves;
        }
        AddMesh(root.transform, "FallenLeaves", $"{TreeFolder}/Tree_FallenLeaves.fbx", leaves);

        var grass = GetMaterial("TreeGrass", Color.white, 0.15f, 0f);
        grass.SetTexture("_BaseMap", LoadTexture($"{TreeFolder}/Textures/grass.png", false));
        grass.SetFloat("_Cull", (float)CullMode.Off);
        grass.doubleSidedGI = true;
        EditorUtility.SetDirty(grass);
        var tuft = AddMesh(root.transform, "Grass", $"{TreeFolder}/Tree_Grass.fbx", grass);
        if (tuft != null)
            tuft.GetComponent<MeshRenderer>().shadowCastingMode = ShadowCastingMode.Off;
    }

    static Texture2D LoadTexture(string path, bool normalMap)
    {
        if (normalMap && AssetImporter.GetAtPath(path) is TextureImporter importer
            && importer.textureType != TextureImporterType.NormalMap)
        {
            importer.textureType = TextureImporterType.NormalMap;
            importer.SaveAndReimport();
        }
        var tex = AssetDatabase.LoadAssetAtPath<Texture2D>(path);
        if (tex == null)
            Debug.LogError($"Missing texture {path}");
        return tex;
    }

    static GameObject AddMesh(Transform parent, string name, string path, params Material[] materials)
    {
        var mesh = LoadMesh(path);
        if (mesh == null)
        {
            Debug.LogError($"Missing mesh {path}");
            return null;
        }
        var go = new GameObject(name);
        go.transform.SetParent(parent, false);
        go.AddComponent<MeshFilter>().sharedMesh = mesh;
        go.AddComponent<MeshRenderer>().sharedMaterials = materials;
        return go;
    }

    const string CutsceneFolder = "Assets/Models/Cutscene";
    const float CrateHeight = 1.21f;   // including the skids

    // [wood, nails, stencil]
    static Material[] CrateMaterials()
    {
        var wood = GetMaterial("CrateWood", Color.white, 0.2f, 0f);
        wood.SetTexture("_BaseMap", LoadTexture($"{CutsceneFolder}/Textures/wood_albedo.png", false));
        wood.SetTexture("_BumpMap", LoadTexture($"{CutsceneFolder}/Textures/wood_normal.png", true));
        wood.EnableKeyword("_NORMALMAP");
        var nails = GetMaterial("Nails", new Color(0.12f, 0.12f, 0.13f), 0.5f, 1f);
        var stencil = GetMaterial("CrateStencil", Color.white, 0.1f, 0f);
        stencil.SetTexture("_BaseMap", LoadTexture($"{CutsceneFolder}/Textures/stencil.png", false));
        stencil.SetFloat("_AlphaClip", 1f);
        stencil.SetFloat("_Cutoff", 0.4f);
        stencil.EnableKeyword("_ALPHATEST_ON");
        stencil.SetFloat("_Cull", (float)CullMode.Off);
        EditorUtility.SetDirty(wood);
        EditorUtility.SetDirty(stencil);
        return new[] { wood, nails, stencil };
    }

    static GameObject Crate(string name, Transform parent, Vector3 position, float yaw, Material[] m,
                            string mesh = "Crate", string stencilMesh = "Crate_Stencil")
    {
        var crate = AddMesh(parent, name, $"{CutsceneFolder}/{mesh}.fbx", m[0], m[1]);
        if (crate == null) return null;
        crate.transform.localPosition = position;
        crate.transform.localRotation = Quaternion.Euler(0f, yaw, 0f);
        crate.AddComponent<BoxCollider>();
        if (stencilMesh == null) return crate;
        var stencil = AddMesh(crate.transform, "Stencil", $"{CutsceneFolder}/{stencilMesh}.fbx", m[2]);
        if (stencil != null)
            stencil.GetComponent<MeshRenderer>().shadowCastingMode = ShadowCastingMode.Off;
        return crate;
    }

    // Closed van cargo area with the player's crate and a few others; the cutscene camera sits in the crate.
    // Blender (x, y, z) maps to Unity (-x, z, -y): the rear doors are at z = 0 and face +Z.
    static void CutsceneVan(Vector3 position, Material[] crates)
    {
        var root = new GameObject("CutsceneVan");
        root.transform.position = position;

        var steel = GetMaterial("VanSteel", Color.white, 0.35f, 0.4f);
        steel.SetTexture("_BaseMap", LoadTexture($"{CutsceneFolder}/Textures/metal_albedo.png", false));
        steel.SetTexture("_BumpMap", LoadTexture($"{CutsceneFolder}/Textures/metal_normal.png", true));
        steel.EnableKeyword("_NORMALMAP");
        var floor = GetMaterial("VanFloor", new Color(0.45f, 0.4f, 0.36f), 0.15f, 0f);
        floor.SetTexture("_BaseMap", LoadTexture($"{CutsceneFolder}/Textures/wood_albedo.png", false));
        EditorUtility.SetDirty(steel);
        EditorUtility.SetDirty(floor);

        var shell = AddMesh(root.transform, "Cargo", $"{CutsceneFolder}/VanCargo.fbx", steel, floor);
        if (shell != null)  // walls and floor the loose crates can crash into
            shell.AddComponent<MeshCollider>().sharedMesh = shell.GetComponent<MeshFilter>().sharedMesh;
        var doorL = AddMesh(root.transform, "Door_L", $"{CutsceneFolder}/VanDoor_L.fbx", steel);
        var doorR = AddMesh(root.transform, "Door_R", $"{CutsceneFolder}/VanDoor_R.fbx", steel);
        foreach (var (door, x) in new[] { (doorL, 1.2f), (doorR, -1.2f) })
        {
            if (door == null) continue;
            door.transform.localPosition = new Vector3(x, 0f, 0f);
            door.AddComponent<MeshCollider>().sharedMesh = door.GetComponent<MeshFilter>().sharedMesh;
        }

        const float floorTop = 0.024f, lowHeight = 0.36f;
        // the player's crate is stacked on two flat crates at the front of the cargo area, so from inside
        // it you look down the van over the other crates and out of the rear-door windows
        // the van is exactly two crates wide: right column at x 0.55, left column at x -0.6
        var stash = new Vector3(0.55f, floorTop, -3f);
        Crate("Crate_Low_1", root.transform, stash, 0f, crates, "Crate_Low", null);
        Crate("Crate_Low_2", root.transform, stash + Vector3.up * lowHeight, 0f, crates, "Crate_Low", null);
        var hero = Crate("Crate_Player", root.transform, stash + Vector3.up * 2f * lowHeight, 0f, crates);
        // the rest of the cargo, kept below the line of sight to the windows; loose for the crash
        var cargo = new List<Rigidbody>();
        void Loose(GameObject c, float mass)
        {
            if (c == null) return;
            var rb = c.AddComponent<Rigidbody>();
            rb.mass = mass;
            rb.isKinematic = true;
            cargo.Add(rb);
        }
        Loose(Crate("Crate_2", root.transform, new Vector3(0.55f, floorTop, -1.3f), 0f, crates), 60f);
        Loose(Crate("Crate_3", root.transform, new Vector3(-0.6f, floorTop, -1.25f), 0f, crates), 60f);
        Loose(Crate("Crate_4", root.transform, new Vector3(-0.6f, floorTop, -2.8f), 0f, crates), 60f);
        Loose(Crate("Crate_Low_3", root.transform, new Vector3(-0.6f, floorTop + CrateHeight, -2.8f), -4f, crates, "Crate_Low", null), 25f);
        if (hero == null) return;

        // crouched close to the crate's slats, looking down the van toward the rear doors (+Z)
        var eye = new GameObject("Eye").transform;
        eye.SetParent(hero.transform, false);
        eye.localPosition = new Vector3(0f, 0.62f, 0.3f);

        var camGo = new GameObject("CutsceneCamera");
        camGo.transform.SetParent(root.transform, false);
        var cam = camGo.AddComponent<Camera>();
        cam.fieldOfView = 70f;
        cam.nearClipPlane = 0.02f;
        cam.farClipPlane = 200f;
        cam.enabled = false;

        var cutscene = root.AddComponent<CrateCutscene>();
        cutscene.cutsceneCamera = cam;
        cutscene.eye = eye;
        cutscene.van = root.transform;
        cutscene.cargo = cargo.ToArray();
        NightStreetSet(root.transform, cutscene);
    }

    // The night street behind the van: road, pavements, lit building fronts and lamp posts on looping
    // 20 m segments, and a moon. Van-local: +Z is behind the van.
    static void NightStreetSet(Transform van, CrateCutscene cutscene)
    {
        const float road = -0.62f;   // road surface below the cargo floor
        const int segments = 6;
        const float segLen = 20f;
        var rng = new System.Random(12);

        var asphalt = GetMaterial("Asphalt", Color.white, 0.25f, 0f);
        asphalt.SetTexture("_BaseMap", LoadTexture($"{CutsceneFolder}/Textures/asphalt.png", false));
        asphalt.SetTextureScale("_BaseMap", new Vector2(1f, 5f));
        var pavement = GetMaterial("Pavement", new Color(0.22f, 0.22f, 0.23f), 0.15f, 0f);
        var facade = GetMaterial("Facade", Color.white, 0.2f, 0f);
        facade.SetTexture("_BaseMap", LoadTexture($"{CutsceneFolder}/Textures/facade_albedo.png", false));
        facade.SetTexture("_EmissionMap", LoadTexture($"{CutsceneFolder}/Textures/facade_emission.png", false));
        facade.SetColor("_EmissionColor", Color.white * 1.6f);
        facade.EnableKeyword("_EMISSION");
        facade.globalIlluminationFlags = MaterialGlobalIlluminationFlags.None;
        var poleMat = GetMaterial("LampPole", new Color(0.08f, 0.08f, 0.09f), 0.4f, 0.8f);
        var lampGlow = Glow("LampGlow", new Color(1f, 0.75f, 0.45f), 6f);
        foreach (var m in new[] { asphalt, facade }) EditorUtility.SetDirty(m);

        var root = new GameObject("NightStreet").transform;
        root.SetParent(van, false);
        var segs = new Transform[segments];
        var lamps = new List<Light>();
        var block = new MaterialPropertyBlock();
        for (int i = 0; i < segments; i++)
        {
            var seg = new GameObject($"Segment{i}").transform;
            seg.SetParent(root, false);
            seg.localPosition = new Vector3(0f, 0f, i * segLen);
            segs[i] = seg;
            NoCollider(Part(PrimitiveType.Cube, "Road", seg, new Vector3(0f, road - 0.05f, segLen / 2f), new Vector3(8f, 0.1f, segLen), asphalt));
            foreach (int side in new[] { -1, 1 })
            {
                NoCollider(Part(PrimitiveType.Cube, "Pavement", seg, new Vector3(side * 5f, road + 0.07f, segLen / 2f), new Vector3(2f, 0.24f, segLen), pavement));
                // two or three buildings per side, of different heights
                float z = 0f;
                while (z < segLen - 1f)
                {
                    float w = Mathf.Min(segLen - z, 5f + (float)rng.NextDouble() * 5f);
                    float h = 6f + (float)rng.NextDouble() * 12f;
                    var b = NoCollider(Part(PrimitiveType.Cube, "Building", seg,
                        new Vector3(side * 10f, road + h / 2f, z + w / 2f), new Vector3(8f, h, w - 0.3f), facade));
                    block.SetVector("_BaseMap_ST", new Vector4(w / 8f, h / 16f, (float)rng.NextDouble(), 0f));
                    b.GetComponent<MeshRenderer>().SetPropertyBlock(block);
                    z += w;
                }
            }
            // one lamp post per segment, alternating sides
            int ls = i % 2 == 0 ? 1 : -1;
            var lampRoot = new GameObject("LampPost").transform;
            lampRoot.SetParent(seg, false);
            lampRoot.localPosition = new Vector3(ls * 4.4f, road, segLen / 2f);
            NoCollider(Part(PrimitiveType.Cylinder, "Pole", lampRoot, new Vector3(0f, 2.6f, 0f), new Vector3(0.14f, 2.6f, 0.14f), poleMat));
            NoCollider(Part(PrimitiveType.Cube, "Arm", lampRoot, new Vector3(-ls * 0.6f, 5.15f, 0f), new Vector3(1.3f, 0.08f, 0.08f), poleMat));
            NoCollider(Part(PrimitiveType.Sphere, "Lamp", lampRoot, new Vector3(-ls * 1.15f, 5.02f, 0f), new Vector3(0.35f, 0.18f, 0.35f), lampGlow));
            var light = new GameObject("LampLight").AddComponent<Light>();
            light.transform.SetParent(lampRoot, false);
            light.transform.localPosition = new Vector3(-ls * 1.15f, 4.9f, 0f);
            light.transform.localRotation = Quaternion.Euler(90f, 0f, 0f);
            light.type = LightType.Spot;
            light.spotAngle = 110f;
            light.range = 9f;
            light.intensity = 7f;
            light.color = new Color(1f, 0.72f, 0.42f);
            light.shadows = LightShadows.None;
            lamps.Add(light);
        }
        var street = root.gameObject.AddComponent<NightStreet>();
        street.segments = segs;
        street.segmentLength = segLen;
        street.lampLights = lamps.ToArray();

        // a car far behind with its headlights on
        var headGlow = Glow("HeadlightGlow", new Color(0.95f, 0.97f, 1f), 10f);
        var car = new GameObject("DistantCar").transform;
        car.SetParent(van, false);
        car.localPosition = new Vector3(-1.2f, road, 42f);
        foreach (int side in new[] { -1, 1 })
            NoCollider(Part(PrimitiveType.Sphere, "Headlight", car, new Vector3(side * 0.7f, 0.65f, 0f), new Vector3(0.3f, 0.18f, 0.12f), headGlow));
        var beams = new GameObject("Beams").AddComponent<Light>();
        beams.transform.SetParent(car, false);
        beams.transform.localPosition = new Vector3(0f, 0.7f, -0.2f);
        beams.transform.localRotation = Quaternion.Euler(4f, 180f, 0f);  // along the road toward the van
        beams.type = LightType.Spot;
        beams.spotAngle = 50f;
        beams.range = 22f;                                                 // lights the road, never reaches the van
        beams.intensity = 6f;
        beams.color = new Color(0.9f, 0.94f, 1f);
        beams.shadows = LightShadows.None;
        cutscene.distantCar = car;

        var moon = new GameObject("Moon").AddComponent<Light>();
        moon.transform.SetParent(van, false);
        moon.transform.localRotation = Quaternion.Euler(32f, 200f, 0f);
        moon.type = LightType.Directional;
        moon.color = new Color(0.55f, 0.65f, 1f);
        moon.intensity = 0.35f;
        moon.shadows = LightShadows.Soft;
        moon.enabled = false;

        cutscene.street = street;
        cutscene.moon = moon;
    }

    static Material Glow(string name, Color color, float strength)
    {
        var m = GetMaterial(name, color, 0.5f, 0f);
        m.SetColor("_EmissionColor", color * strength);
        m.EnableKeyword("_EMISSION");
        m.globalIlluminationFlags = MaterialGlobalIlluminationFlags.None;
        EditorUtility.SetDirty(m);
        return m;
    }

    static GameObject NoCollider(GameObject go)
    {
        Object.DestroyImmediate(go.GetComponent<Collider>());
        return go;
    }

    // A bust mesh (base at its origin, facing -Z) on a 1 m stone pedestal standing on the plaza.
    static GameObject Bust(string name, Transform parent, Vector3 position, Material marble, Material stone)
    {
        const float plaza = 0.1f, pedestal = 1f;
        var root = new GameObject(name).transform;
        root.SetParent(parent, false);
        root.localPosition = position;
        Part(PrimitiveType.Cube, "Pedestal", root, new Vector3(0f, plaza + pedestal / 2f, 0f), new Vector3(0.55f, pedestal, 0.45f), stone);

        var mesh = LoadMesh($"Assets/Models/Statues/{name}.obj");
        if (mesh == null)
        {
            Debug.LogError($"Missing bust mesh Assets/Models/Statues/{name}.obj");
            return root.gameObject;
        }
        var bust = new GameObject("Bust");
        bust.transform.SetParent(root, false);
        bust.transform.localPosition = new Vector3(0f, plaza + pedestal, 0f);
        bust.AddComponent<MeshFilter>().sharedMesh = mesh;
        bust.AddComponent<MeshRenderer>().sharedMaterial = marble;
        bust.AddComponent<MeshCollider>().sharedMesh = mesh;

        // optional marble cloth draped over the body
        var drapeMesh = LoadMesh($"Assets/Models/Statues/{name}_Drape.obj");
        if (drapeMesh != null)
        {
            var drape = new GameObject("Drape");
            drape.transform.SetParent(bust.transform, false);
            drape.AddComponent<MeshFilter>().sharedMesh = drapeMesh;
            drape.AddComponent<MeshRenderer>().sharedMaterial = marble;
        }
        return root.gameObject;
    }

    static Mesh LoadMesh(string path)
    {
        foreach (var asset in AssetDatabase.LoadAllAssetsAtPath(path))
            if (asset is Mesh mesh)
                return mesh;
        return null;
    }

    static GameObject Part(PrimitiveType type, string name, Transform parent, Vector3 pos, Vector3 scale, Material mat)
    {
        var go = GameObject.CreatePrimitive(type);
        go.name = name;
        go.transform.SetParent(parent, false);
        go.transform.localPosition = pos;
        go.transform.localScale = scale;
        go.GetComponent<Renderer>().sharedMaterial = mat;
        return go;
    }

    static Material GetMaterial(string name, Color color, float smoothness, float metallic)
    {
        if (!AssetDatabase.IsValidFolder(MaterialFolder))
            AssetDatabase.CreateFolder("Assets", "Materials");

        string assetPath = $"{MaterialFolder}/{name}.mat";
        var mat = AssetDatabase.LoadAssetAtPath<Material>(assetPath);
        if (mat == null)
        {
            var shader = Shader.Find("Universal Render Pipeline/Lit") ?? Shader.Find("Standard");
            mat = new Material(shader);
            AssetDatabase.CreateAsset(mat, assetPath);
        }
        mat.SetColor("_BaseColor", color);
        mat.color = color;
        mat.SetFloat("_Smoothness", smoothness);
        mat.SetFloat("_Metallic", metallic);
        EditorUtility.SetDirty(mat);
        AssetDatabase.SaveAssets();
        return mat;
    }

    static void AddToBuildSettings(string path)
    {
        var scenes = new List<EditorBuildSettingsScene>(EditorBuildSettings.scenes);
        if (scenes.Exists(s => s.path == path)) return;
        scenes.Add(new EditorBuildSettingsScene(path, true));
        EditorBuildSettings.scenes = scenes.ToArray();
    }
}
